    /// <summary>按累计经验、自然星级（2-5）和当前星级换算等级；数据不足时返回 null。</summary>
    public static int? ResolveLevel(long exp, int rarity, int grade)
    {
        var table = rarity switch
        {
            2 => Natural2,
            3 => Natural3,
            4 => Natural4,
            5 => Natural5,
            _ => null,
        };
        if (table == null || grade is < 1 or > 6)
            return null;
        var cap = Math.Min(grade * 10, 60);
        exp = Math.Max(exp, 0);
        var level = 1;
        for (var index = 2; index <= cap && index < table.Length; index++)
        {
            if (table[index] > exp)
                break;
            level = index;
        }
        return level;
    }
